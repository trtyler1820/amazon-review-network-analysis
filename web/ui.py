def plotly_layout(**overrides) -> dict:
    """Shared Plotly layout dict. Pass any kwarg to override specific keys."""
    base = dict(
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        font=dict(
            family=FONT_STACK,
            color=PALETTE["text_muted"],
            size=12.5,
        ),
        title=dict(
            font=dict(
                family=FONT_STACK,
                size=15,
                color=PALETTE["text"],
            ),
            x=0.01,
            xanchor="left",
            y=0.97,
            yanchor="top",
        ),
        margin=dict(l=10, r=10, t=54, b=10),
        xaxis=dict(
            gridcolor="rgba(255,255,255,0.05)",
            zerolinecolor="rgba(255,255,255,0.08)",
            linecolor="rgba(255,255,255,0.12)",
            tickfont=dict(size=11, color=PALETTE["text_muted"]),
            title=dict(font=dict(size=12, color=PALETTE["text_muted"])),
        ),
        yaxis=dict(
            gridcolor="rgba(255,255,255,0.05)",
            zerolinecolor="rgba(255,255,255,0.08)",
            linecolor="rgba(255,255,255,0.12)",
            tickfont=dict(size=11, color=PALETTE["text_muted"]),
            title=dict(font=dict(size=12, color=PALETTE["text_muted"])),
        ),
        legend=dict(
            bgcolor="rgba(0,0,0,0)",
            font=dict(color=PALETTE["text_muted"], size=11),
            bordercolor="rgba(255,255,255,0.08)",
        ),
        hoverlabel=dict(
            bgcolor=PALETTE["bg_elev"],
            bordercolor=PALETTE["border_strong"],
            font=dict(family=FONT_STACK, color=PALETTE["text"], size=12),
        ),
        colorway=CHART_PALETTE,
    )
    # Nested overrides: let callers pass e.g. margin=dict(t=30) without losing
    # the other defaults. We merge shallowly for dict values.
    for k, v in overrides.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            merged = dict(base[k])
            merged.update(v)
            base[k] = merged
        else:
            base[k] = v
    return base


def style_plotly(fig, **overrides):
    """Apply shared theming to a Plotly figure. Returns the figure."""
    fig.update_layout(**plotly_layout(**overrides))
    # Restyle colorbars to match dark theme
    fig.update_coloraxes(
        colorbar=dict(
            tickfont=dict(color=PALETTE["text_muted"], size=10.5),
            outlinewidth=0,
            thickness=12,
            len=0.85,
        )
    )
    return fig


# ---------------------------------------------------------------------------
# Matplotlib dark treatment (used by the network graph + cluster diagnostics)
# ---------------------------------------------------------------------------

def mpl_color(color: str) -> Tuple[float, float, float, float] | str:
    """
    Convert a CSS-style ``rgba(r, g, b, a)`` or ``rgb(r, g, b)`` string to the
    0-1 float tuple matplotlib accepts. Hex strings and named colors are
    passed through unchanged. Matplotlib rejects CSS-style ``rgba(...)`` —
    this shim lets us reuse the Plotly-oriented PALETTE values here.
    """
    s = color.strip()
    if s.startswith(("rgba(", "rgb(")) and s.endswith(")"):
        inner = s[s.index("(") + 1 : -1]
        parts = [p.strip() for p in inner.split(",")]
        try:
            r = float(parts[0]) / 255.0
            g = float(parts[1]) / 255.0
            b = float(parts[2]) / 255.0
            a = float(parts[3]) if len(parts) == 4 else 1.0
            return (max(0.0, min(1.0, r)),
                    max(0.0, min(1.0, g)),
                    max(0.0, min(1.0, b)),
                    max(0.0, min(1.0, a)))
        except (ValueError, IndexError):
            return s
    return s


def matplotlib_dark(fig, ax) -> None:
    """Retheme a matplotlib axes to the dashboard's dark palette."""
    text_muted = mpl_color(PALETTE["text_muted"])
    text = mpl_color(PALETTE["text"])
    border = mpl_color(PALETTE["border"])
    grid = mpl_color("rgba(255,255,255,0.05)")

    fig.patch.set_facecolor("#12121a")
    ax.set_facecolor("#12121a")
    ax.tick_params(colors=text_muted, labelsize=9)
    for spine in ax.spines.values():
        spine.set_color(border)
        spine.set_linewidth(0.8)
    ax.xaxis.label.set_color(text_muted)
    ax.yaxis.label.set_color(text_muted)
    if ax.get_title():
        ax.set_title(ax.get_title(), color=text, fontsize=12, fontweight="600")
    ax.grid(True, color=grid, linewidth=0.8)
