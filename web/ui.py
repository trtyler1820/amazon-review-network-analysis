def render_glass_card(title: Optional[str], body_html: str) -> None:
    """Render an HTML glass card. `body_html` is used as-is — caller escapes."""
    title_html = ""
    if title:
        title_html = f'<div class="ar-card-title">{_html.escape(title)}</div>'
