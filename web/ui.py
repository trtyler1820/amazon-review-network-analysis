def render_page_header(
    title: str,
    *,
    eyebrow: Optional[str] = None,
    subtitle: Optional[str] = None,
) -> None:
    """
    Lighter page banner used by every page except Overview.

    Keeps the animated-paths motif in the background at reduced opacity, with
    a gradient-text title. No per-letter stagger (reserved for the hero) — a
    single restrained entrance so the dashboard doesn't feel like 6 landings.
    """
    eyebrow_html = ""
    if eyebrow:
        eyebrow_html = (
            f'<div class="ar-page-eyebrow">{_html.escape(eyebrow)}</div>'
        )

    subtitle_html = ""
    if subtitle:
        subtitle_html = (
            f'<p class="ar-page-subtitle">{subtitle}</p>'  # allow markdown-ish in subtitle
        )

    paths_svg = _build_paths_svg(variant="header")

    html = f'''
<div class="ar-page-header">
  <svg class="ar-page-header-paths" viewBox="0 0 696 180"
       preserveAspectRatio="xMidYMid slice" aria-hidden="true">
    <title>Background Paths</title>
    {paths_svg}
  </svg>
  <div class="ar-page-header-content">
    {eyebrow_html}
    <h1 class="ar-page-title">{_html.escape(title)}</h1>
    {subtitle_html}
  </div>
</div>
'''
    st.markdown(html, unsafe_allow_html=True)


