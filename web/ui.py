# ---------------------------------------------------------------------------
# Background paths SVG generator (port of the React BackgroundPaths formula)
# ---------------------------------------------------------------------------

def _build_paths_svg(
    *,
    count: int = 36,
    variant: str = "hero",
) -> str:
    """
    Build the SVG <path> list for the background-paths motif.

    Parameters
    ----------
    count : int
        Paths per orientation. 36 matches the React reference.
    variant : "hero" | "header"
        "hero"   — full range of opacities and widths; longer durations.
        "header" — compressed, subtler for secondary pages.

    Each path carries CSS custom properties (--op, --dur, --d) consumed by
    the keyframes in web/styles.py.
    """
    lines: list[str] = []
    for position in (1, -1):
        for i in range(count):
            d = (
                f"M-{380 - i * 5 * position} -{189 + i * 6}"
                f"C-{380 - i * 5 * position} -{189 + i * 6} "
                f"-{312 - i * 5 * position} {216 - i * 6} "
                f"{152 - i * 5 * position} {343 - i * 6}"
                f"C{616 - i * 5 * position} {470 - i * 6} "
                f"{684 - i * 5 * position} {875 - i * 6} "
                f"{684 - i * 5 * position} {875 - i * 6}"
            )
            if variant == "header":
                opacity = 0.10 + i * 0.012
                width = 0.4 + i * 0.025
                dur = 26 + ((i * 7 + (0 if position == 1 else 11)) % 12)
            else:  # hero
                opacity = 0.10 + i * 0.018
                width = 0.5 + i * 0.030
                dur = 20 + ((i * 13 + (0 if position == 1 else 7)) % 10)

            delay = (i * 0.09 + (0 if position == 1 else 0.4)) % 6
            lines.append(
                f'<path d="{d}" '
                f'stroke-width="{width:.2f}" '
                f'style="--op:{opacity:.3f};--dur:{dur}s;--d:{delay:.2f}s;'
                f'opacity:{opacity:.3f};" />'
            )
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Staggered-letter title
# ---------------------------------------------------------------------------

def _split_letters(title: str, base_delay_ms: int = 220) -> str:
    """
    Split `title` into word spans, each containing per-letter spans with
    staggered animation delays. Safe-encodes user text.
    """
    words = title.split(" ")
    html_out: list[str] = []
    for wi, word in enumerate(words):
        letter_spans: list[str] = []
        for li, letter in enumerate(word):
            delay = base_delay_ms + wi * 95 + li * 34
            letter_spans.append(
                f'<span class="ar-letter" style="--delay:{delay}ms">'
                f'{_html.escape(letter)}</span>'
            )
        html_out.append(f'<span class="ar-word">{"".join(letter_spans)}</span>')
    return "".join(html_out)


# ---------------------------------------------------------------------------
# Hero
# ---------------------------------------------------------------------------

def render_hero(
    title: str,
    *,
    eyebrow: Optional[str] = None,
    subtitle: Optional[str] = None,
    stats: Optional[Sequence[Tuple[str, str]]] = None,
) -> None:
    """
    Render the cinematic landing hero (Overview page only).

    Args:
        title:     Short title, 2–4 words recommended. Animated per-letter.
        eyebrow:   Optional small label above the title (pill style).
        subtitle:  Optional subtitle below the title.
        stats:     Optional list of (value, label) tuples rendered as a stat row.
    """
    eyebrow_html = ""
    if eyebrow:
        eyebrow_html = (
            f'<div class="ar-eyebrow">{_html.escape(eyebrow)}</div>'
        )

    subtitle_html = ""
    if subtitle:
        subtitle_html = (
            f'<p class="ar-hero-subtitle">{_html.escape(subtitle)}</p>'
        )

    stats_html = ""
    if stats:
        items = "".join(
            f'<div class="ar-hero-stat">'
            f'<span class="ar-hero-stat-value">{_html.escape(v)}</span>'
            f'<span class="ar-hero-stat-label">{_html.escape(lbl)}</span>'
            f'</div>'
            for v, lbl in stats
        )
        # Wrap the stat row in an opaque glass panel so the animated paths
        # underneath can't undermine readability.
        stats_html = f'<div class="ar-hero-stats-panel"><div class="ar-hero-stats">{items}</div></div>'

    title_html = _split_letters(title)
    paths_svg = _build_paths_svg(variant="hero")

    html = f'''
<div class="ar-hero">
  <svg class="ar-hero-paths" viewBox="0 0 696 316"
       preserveAspectRatio="xMidYMid slice" aria-hidden="true">
    <title>Background Paths</title>
    {paths_svg}
  </svg>
  <div class="ar-hero-content">
    {eyebrow_html}
    <h1 class="ar-hero-title">{title_html}</h1>
    {subtitle_html}
    {stats_html}
  </div>
</div>
'''
    st.markdown(html, unsafe_allow_html=True)


