"""
Reusable presentation primitives for the Streamlit dashboard.

Public API:
  inject_global_styles()          -- injects the stylesheet (re-exported from styles.py)
  render_hero(...)                -- cinematic landing hero (Overview only)
  render_page_header(...)         -- lighter page banner
  render_sidebar_brand(...)       -- sidebar wordmark (image-based)
  render_glass_card(title, body)  -- small HTML glass card
  render_explainer_card(...)      -- explanation-first card; live value lives in the tooltip
  plotly_layout(**overrides)      -- shared Plotly layout dict
  style_plotly(fig, **overrides)  -- apply theme to a Plotly figure in one call
  matplotlib_dark(fig, ax)        -- retheme a matplotlib axes to dark

The BackgroundPaths SVG motif is generated by `_build_paths_svg()` using the
same formula as the React reference, so the geometry matches exactly. Motion
is driven by CSS keyframes (see web/styles.py) — no JavaScript needed.
"""

from __future__ import annotations

import base64 as _base64
