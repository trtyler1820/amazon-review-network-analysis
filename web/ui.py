_ASSETS_DIR = _os.path.join(_os.path.dirname(__file__), "assets")
_SIDEBAR_BRAND_PATH = _os.path.join(_ASSETS_DIR, "sidebar-brand.png")


def _encode_image_as_data_uri(path: str) -> Optional[str]:
    """Read a PNG from disk and return a base64 data URI, or None if missing."""
    if not _os.path.isfile(path):
        return None
    with open(path, "rb") as f:
        payload = _base64.b64encode(f.read()).decode("ascii")
    return f"data:image/png;base64,{payload}"


def render_sidebar_brand() -> None:
    """
    Render the sidebar wordmark using ``web/assets/sidebar-brand.png``.

    The PNG is transparent, so it sits cleanly on the dark sidebar gradient.
    Falls back to a text wordmark if the asset is missing so the app still
    renders on a fresh clone before the asset is placed.
    """
    data_uri = _encode_image_as_data_uri(_SIDEBAR_BRAND_PATH)
    if data_uri:
        st.sidebar.markdown(
            f'''
<div class="ar-sidebar-brand">
  <img src="{data_uri}" alt="Amazon Reviews" />
  <div class="ar-sidebar-brand-kicker">Reviews Analytics Dashboard</div>
</div>
''',
            unsafe_allow_html=True,
        )
        return

    # Asset missing — fall back to a minimal text wordmark so the app still
    # boots on a fresh clone before web/assets/sidebar-brand.png is placed.
    st.sidebar.markdown(
        '''
<div class="ar-sidebar-brand ar-sidebar-brand-fallback">
  <div class="ar-sidebar-brand-title">Amazon Reviews</div>
  <div class="ar-sidebar-brand-kicker">Reviews Analytics Dashboard</div>
</div>
''',
        unsafe_allow_html=True,
    )


